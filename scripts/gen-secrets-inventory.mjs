#!/usr/bin/env node
// Generates supabase/SECRETS-INVENTORY.md from the actual Deno.env.get(...)
// usage across the edge functions (project-review PR#98). The curated
// supabase/SECRETS.md explains where to set each secret and what breaks
// without it; this GENERATED companion guarantees the which-function-needs-
// what mapping never drifts (it claimed "all five edge functions" while the
// repo had grown past 50). Regenerate + commit whenever functions change:
//
//   node scripts/gen-secrets-inventory.mjs
//
// CI could also assert `git diff --exit-code` on the output to force it.

import fs from "node:fs";
import path from "node:path";

const root = path.join(import.meta.dirname, "..");
const fnDir = path.join(root, "supabase", "functions");

const ENV_RE = /Deno\.env\.get\(\s*["'`]([A-Z0-9_]+)["'`]\s*\)/g;

// Walk every .ts file, attribute each env var to the top-level function dir.
const byVar = new Map();     // VAR -> Set(function)
const byFn = new Map();      // function -> Set(VAR)

function walk(dir, fnName) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, fnName ?? entry.name);
    else if (entry.name.endsWith(".ts")) {
      const src = fs.readFileSync(p, "utf8");
      let m;
      while ((m = ENV_RE.exec(src))) {
        const v = m[1];
        const owner = fnName ?? "_shared";
        if (!byVar.has(v)) byVar.set(v, new Set());
        byVar.get(v).add(owner);
        if (!byFn.has(owner)) byFn.set(owner, new Set());
        byFn.get(owner).add(v);
      }
    }
  }
}

for (const entry of fs.readdirSync(fnDir, { withFileTypes: true })) {
  if (entry.isDirectory()) walk(path.join(fnDir, entry.name), entry.name === "_shared" ? "_shared" : entry.name);
}

const vars = [...byVar.keys()].sort();
const fns = [...byFn.keys()].sort();

let out = `<!-- GENERATED by scripts/gen-secrets-inventory.mjs — do not edit by hand.
     Regenerate: node scripts/gen-secrets-inventory.mjs -->

# Edge function env-var inventory (generated)

Scraped from every \`Deno.env.get(...)\` in \`supabase/functions/\`.
${fns.filter((f) => f !== "_shared").length} functions, ${vars.length} distinct env vars.
For where to SET each var and what breaks without it, see \`SECRETS.md\`.

## By env var

| Env var | Used by |
| --- | --- |
`;
for (const v of vars) {
  out += `| \`${v}\` | ${[...byVar.get(v)].sort().join(", ")} |\n`;
}

out += `\n## By function\n\n| Function | Env vars |\n| --- | --- |\n`;
for (const f of fns) {
  out += `| \`${f}\` | ${[...byFn.get(f)].sort().map((v) => "`" + v + "`").join(", ")} |\n`;
}

fs.writeFileSync(path.join(root, "supabase", "SECRETS-INVENTORY.md"), out);
console.log(`✓ SECRETS-INVENTORY.md: ${fns.length} functions, ${vars.length} env vars`);
